# 上下文工程 —— 隔离规则：对话背景和资料分区放置，并明确各自的用途。
# 只有存在对话背景时才注入这段规则，单轮问答的提示词保持精简。
CONVERSATION_RULES = """
    关于【对话背景】：
    - 它只用于理解指代和省略（如"它""上面说的第二点"）、保持前后回答一致、避免重复已经说过的内容。
    - 新的事实性信息必须来自【资料】，不能把对话背景当作资料来源。
    - 只有当用户明确问到此前回答的内容（如"总结一下你刚才说的"）时，才可以复述对话背景里的回答。"""

